// Generates src/avatar/avatarCatalog.gen.ts from the core's avatar_catalog.json (the single source of truth).
// Run `npm run gen:avatar` after editing the catalog; a vitest test fails when the output is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const SOURCE = resolve(here, "../../kali-core/kali_core/avatar_catalog.json");
export const TARGET = resolve(here, "../src/avatar/avatarCatalog.gen.ts");

export function render(sourceText) {
  const catalog = JSON.parse(sourceText);
  // `doc` / `prompt` are core-side only; keep the client bundle lean.
  const { doc: _doc, prompt: _prompt, ...client } = catalog;
  return `// GENERATED by scripts/gen-avatar-catalog.mjs from kali-core/kali_core/avatar_catalog.json. Do not edit.\n` +
    `export const CATALOG = ${JSON.stringify(client, null, 2)} as const;\n\n` +
    `export type ChannelId = keyof typeof CATALOG.channels;\n` +
    `export type ActivityId = keyof typeof CATALOG.activities;\n` +
    `export type EmotionId = keyof typeof CATALOG.emotions;\n` +
    `export type GestureId = keyof typeof CATALOG.gestures;\n` +
    `export type MouthShape = (typeof CATALOG.mouthShapes)[number];\n` +
    `export type SymbolId = (typeof CATALOG.symbols)[number];\n` +
    `export type HaloTone = (typeof CATALOG.haloTones)[number];\n` +
    `export type AttentionId = (typeof CATALOG.attentions)[number];\n` +
    `export type PerfProfileId = keyof typeof CATALOG.perf;\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(TARGET, render(readFileSync(SOURCE, "utf8")));
  console.log("wrote", TARGET);
}
